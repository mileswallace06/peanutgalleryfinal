// ── Defaults (concepts override only what differs) ──────────────────────
const DEFAULT_TYPOGRAPHY = {
  headline:    { font: 'display', weight: 'heavy',  transform: 'none',     tracking: 'normal',     scale: 1.0 },
  subheadline: { font: 'body',    weight: 'normal',  transform: 'none',     tracking: 'normal',     scale: 1.0 },
  body:        { font: 'body',    weight: 'normal',  transform: 'none',     tracking: 'normal',     scale: 1.0 },
  cta:         { font: 'body',    weight: 'bold',    transform: 'uppercase', tracking: 'wide',      scale: 1.0 },
  badge:       { font: 'body',    weight: 'bold',    transform: 'uppercase', tracking: 'extra-wide', scale: 1.0 },
  stat:        { font: 'display', weight: 'heavy',  transform: 'none',     tracking: 'normal',     scale: 1.0 },
};

const DEFAULT_BG = { type: 'radial-glow', baseColor: '#050308', glow: { color: NEON.purple, x: 15, y: -5, intensity: 0.10 } };
const DEFAULT_COMPOSITION = { anchor: 'center', alignment: 'center', negativeSpace: 0.3, maxWidth: 0.85, rotation: 0 };
const DEFAULT_COLOR = { text: 'white', accent: NEON.purple, palette: [NEON.purple, NEON.pink, NEON.green], textGradient: GRADIENTS.headline };
const DEFAULT_TEXTURE = { type: 'none', intensity: 0 };
const DEFAULT_LOGO = { position: 'bottom-center', size: 'sm' };

function concept(data) {
  return {
    id: data.id,
    name: data.name,
    family: data.family,
    inspiration: data.inspiration,
    references: data.references || [],
    mood: data.mood,
    visualLanguage: data.visualLanguage,
    visualMetaphor: data.visualMetaphor,
    focalPoints: data.focalPoints,
    photographyStyle: data.photographyStyle || 'none',
    designSystem: {
      background:   { ...DEFAULT_BG, ...data.designSystem?.background },
      composition:  { ...DEFAULT_COMPOSITION, ...data.designSystem?.composition },
      typography:   { ...DEFAULT_TYPOGRAPHY, ...data.designSystem?.typography },
      color:        { ...DEFAULT_COLOR, ...data.designSystem?.color },
      texture:      { ...DEFAULT_TEXTURE, ...data.designSystem?.texture },
      decorative:   data.designSystem?.decorative || [],
      logo:         { ...DEFAULT_LOGO, ...data.designSystem?.logo },
      hierarchy:    data.designSystem?.hierarchy || ['badge', 'headline', 'subheadline', 'body', 'cta'],
    },
  };
}

