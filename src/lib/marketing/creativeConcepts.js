/**
 * Creative Concepts — Structured Design System Definitions
 * --------------------------------------------------------------------
 * Decision 2 of 3: What visual metaphor best communicates the message?
 *
 * A Creative Concept is NOT a component. It is NOT a layout.
 * It is structured design data that describes a complete art direction.
 *
 * The Creative Direction Engine reads this data and constructs the
 * graphic dynamically. No per-concept rendering code exists.
 *
 * Each concept defines:
 *   - inspiration + references (Inspiration Board)
 *   - mood, visual language, visual metaphor
 *   - a structured designSystem the engine interprets:
 *       background, composition, typography, color, texture,
 *       decorative elements, logo placement, hierarchy
 *
 * The AI extracts design PRINCIPLES from references — it must never
 * recreate or copy them. It blends their characteristics into
 * Peanut Gallery's existing design language.
 */
